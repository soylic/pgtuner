// Command gen writes rules_gen.go: the sorted list of advice IDs found in the checks package.
// Run it with go generate ./internal/checks after adding or renaming an ID.
package main

import (
	"bytes"
	"fmt"
	"go/ast"
	"go/format"
	"go/parser"
	"go/token"
	"os"
	"path/filepath"
	"sort"
	"strconv"
	"strings"
)

func main() {
	dir := "."
	if len(os.Args) > 1 {
		dir = os.Args[1]
	}
	files, err := filepath.Glob(filepath.Join(dir, "*.go"))
	if err != nil {
		fail(err)
	}
	fset := token.NewFileSet()
	seen := map[string]bool{}
	for _, name := range files {
		base := filepath.Base(name)
		if strings.HasSuffix(base, "_test.go") || base == "rules_gen.go" {
			continue
		}
		f, err := parser.ParseFile(fset, name, nil, 0)
		if err != nil {
			fail(err)
		}
		ast.Inspect(f, func(n ast.Node) bool {
			kv, ok := n.(*ast.KeyValueExpr)
			if !ok {
				return true
			}
			if k, ok := kv.Key.(*ast.Ident); ok && k.Name == "ID" {
				if bl, ok := kv.Value.(*ast.BasicLit); ok && bl.Kind == token.STRING {
					id, _ := strconv.Unquote(bl.Value)
					seen[id] = true
				}
			}
			return true
		})
	}
	ids := make([]string, 0, len(seen))
	for id := range seen {
		ids = append(ids, id)
	}
	sort.Strings(ids)

	var b bytes.Buffer
	b.WriteString("// Code generated by go generate ./internal/checks; DO NOT EDIT.\n\npackage checks\n\n")
	b.WriteString("// generatedRuleIDs lists every advice ID found in the source of this package.\n")
	b.WriteString("var generatedRuleIDs = []string{\n")
	for _, id := range ids {
		fmt.Fprintf(&b, "\t%q,\n", id)
	}
	b.WriteString("}\n")
	src, err := format.Source(b.Bytes())
	if err != nil {
		fail(err)
	}
	if err := os.WriteFile(filepath.Join(dir, "rules_gen.go"), src, 0o644); err != nil {
		fail(err)
	}
}

func fail(err error) {
	fmt.Fprintln(os.Stderr, "gen:", err)
	os.Exit(1)
}
